// 思路:
//   题眼连读:「三元凑定值 0」+「答案不重复」+「顺序不重要」。暴力三重
//   循环 O(n^3)(n=3000 约 4.5e9 组)必超。降元:外层定一枚锚 nums[i],
//   剩下两数凑 -nums[i]——正是 167 的对撞搜索(有序数组两数凑定值,和与
//   目标比大小给方向)。排序一刀两用:单调性给对撞方向判据,相邻性把同值
//   挤成连续块、给去重;题面「顺序不重要」白送这一刀。
//   与 167 差在收场:167 唯一答案对,命中即 return;本题命中即收组,跳过
//   l/r 同值块再各走一步,继续走——搜索的多解版,窗口走空自然收场(与 11
//   求最值同款「不 return」收场)。
//   去重两处,缺一必重:i 层 nums[i]==nums[i-1] 跳过(块首当锚那轮已配
//   完全场,块内其余当锚只会重出同样的组);l/r 层命中后跳同值块(同值配
//   谁都同和,块尾代表已试完所有搭档)。l 从 i+1 起:锚不当自己的搭档
//   (不复用),又规定 i<l<r 的字典序——每组只以一种顺序出现,结构性去重,
//   与 80「留 k 份」同宗:同值块只认代表。
//   剪枝(省时,不是正确性依赖):排序后 nums[i]>0 则 l、r 更大,三正数
//   之和必 >0,可直接 break;注意是 >0 不是 >=0(坑6)。
// 复杂度:
//   时间 O(n^2):排序 O(n log n) + 外层 n 枚锚 × 内层对撞 O(n)(l 只增
//   r 只减,合计 <=n);空间 O(1)(不计输出与排序栈)。基线:暴力枚举三元
//   组 O(n^3)(必超);哈希定一枚找两数同为 O(n^2),但去重得靠 set 兜底,
//   排序版用「相邻可跳」把 set 也省了。输出量最坏 Theta(n^2)(如
//   {-m..-1, 1..m} 的 (-a,-b,a+b) 型组),O(n^2) 已贴输出下界。
//   int 够用:|nums[i]| <= 1e5,三数和 |sum| <= 3e5 << INT_MAX。
// 坑:
//   1. 去重两处缺一必重,且各自防的重复形状不同:缺 i 层,[-2,-2,0,2] 把
//      [-2,0,2] 收两遍(同值块多个锚各配一遍,穷举池 34.7% 错);缺 l/r
//      层,[-2,0,0,2,2] 把 [-2,0,2] 收两遍(一个锚的窗口里同值对多对,池
//      8.0% 错);两处都关 40.4% 错。随机池(n<=14)对应 49.0%/28.7%/54.1%。
//   2. i 层去重看错边:前瞻 nums[i]==nums[i+1] 把块首代表也跳了,
//      [-1,-1,2] 输出 [] 丢掉唯一解(池 29.0% 错)。块首是配得最全的锚
//      (它那轮扫过全场含块内),去重只该跳「跟在块首后面的同值」——比前
//      一枚 nums[i-1],不是比后一枚。
//   3. 跳同值块放在判据前(先跳后比)不等价:提前跳吃掉「还没配过对」的
//      块员。[-2,-2,1,1]:i=0,l=1,r=3,r 的块在比较前被从 3 跳到 2,答案
//      对 (2,3) 再没机会配,输出 [] 丢唯一解 (-2,1,1)(池 21.9% 错)。跳块
//      必须放在命中之后:先收该收的,跳掉的才是「已收同款」。
//   4. 命中后只跳同值块、忘 l++/r--:无相邻同值时两枚指针原地不动,命中
//      再命中,死循环。标本 [0,-1,1](排序后 [-1,0,1],i=0 命中 (1,2),
//      两枚皆无同值邻,块跳空转,永久收集;池 65.9% 错全是这种挂)。跳块的
//      while 有守卫不会越界——死在「不动」,不是 125 那种死在「越界」。
//   5. l 从 0 起(不从 i+1):锚自己当搭档,元素复用——[-1,0,2] 错出
//      (-1,-1,2)(输入只有一个 -1,池 63.2% 错);判官示例 1 还多收乱序组
//      (0,-1,1)。l=i+1 一并解决复用与乱序。
//   6. 剪枝边界:nums[i]>=0 的 break 把判官示例 3 [0,0,0] 剪成 [](池
//      8.9% 错,失败集恰好=需要 0 当锚的用例)。锚为 0 时 l、r 仍可为 0;
//      必须 >0——锚为正,l、r 更大,三正之和才必 >0。
//   7. 不排序直接对撞:方向判据(sum 大了收 r)建立在有序上,未排序方向
//      乱走,漏解错解齐来([0,-1,1] 原样能漏掉判官示例,池 74.6% 错),连
//      组内顺序都是乱的((0,-1,1) 这种乱序组也收)。排序是这题的地基,
//      不是优化。
//   8. (问答成果,未爆)循环边界 i<n-2 放宽成 i<n:输出一字不差(池 39500
//      例 0 差),只是白跑两轮空锚——i=n-2 时 l=r=n-1,i=n-1 时 l=n>r,
//      内层 while(l<r) 一次不进,nums[l]/nums[r] 一下都没碰。安全不是
//      i<n 白给的,是 while 判在访前给的(125 守卫在前同宗);再松一步
//      i<=n 就真爆:i=n 时 nums[i]==nums[i-1] 在 while 之前访 nums[n],
//      C++ 无声越界读 UB,Python 转写响亮 IndexError(池 1598 例=数组
//      最大值 <= 0、锚循环一路活到 i=n 的输入,最小标本 [-2,-2,-2];
//      含正数的输入被剪枝提前 break 兜住)。i<n-2 的价值是把「锚后至少
//      留两格」写进边界——循环边界即文档。
//   9. (自敲标本,语言层,响亮)res.push_back(nums[i],nums[l],nums[r]) 三实参
//      编译不过:push_back 只收「一件货」——vector<vector<int>> 的元素是
//      整个 vector<int>,三件 int 要先打包成一件:res.push_back({nums[i],
//      nums[l],nums[r]}),大括号在这里是一个 vector<int> 的字面量。一响一
//      静对照:这条编译期就拦下,坑10 编译过了判官才拦。
//  10. (自敲标本,算法层,静默)命中后跳同值块用 if 代 while:if 只跳一步,
//      块长 <=2 恰好够(if 一步+走步一步正好过完两格);块长 >=3 时 l/r 还
//      停在块内,下一轮同和再命中,重收同款三元组。标本 [-2,0,0,0,2,2,2]:
//      i=0 命中 (1,6) 收 (-2,0,2),l 经 if 跳+走步落在 3(还在 0-块内),r 落
//      在 4(还在 2-块内),l=3<r=4,0+2=2 再命中重收。穷举:长度 <=6 池
//      19500 例 0 错——重收需双侧块长都 >=3,锚 1+块 3+块 3 至少 7 格,判官
//      三示例最长 6 格全过;长度 7 池 323/78125 错,随机池(n 7..16)8.9%。
//      修法:if→while,且守卫 l<r 必须补上——原 if 单步由外层 l<r 兜住界内
//      (nums[l+1]<=nums[r] 恒真,池 0 越界);while 多步会一路读到 nums[n]
//      (忘守卫版同池 2012/19500 例 Python 响亮 IndexError,C++ 无声 UB)。
//      同一行,步数不同,守卫需求不同。
//  11. (自敲标本二交,语言层,UB)守卫站错 && 右侧:while(nums[l+1]==nums[l]
//      && l<r)——&& 从左到右求值短路,nums[l+1] 排在 l<r 前面,先访问后
//      判界,守卫形同虚设。命中时 l 的同值块铺到数组末尾,l 一路 ++ 到
//      n-1,下一轮条件先读 nums[n]:ASAN heap-buffer-overflow READ of
//      size 4,判官 [0,0,0,0] 于 11/316 爆(判官示例3 [0,0,0] 同形同炸,
//      只是测试序里它没先到;穷举最小标本 [-2,1,1] 仅 3 格,池 2012/19500
//      例=10.3% 炸;不炸的输入输出全对=坑9-10 修得干净)。修法:守卫换左
//      while(l<r&&nums[l+1]==nums[l])——「守卫在前」细化到 && 的左操作数,
//      判先于访就安全,访先于判才要命。r 侧 while(nums[r-1]==nums[r]&&l<r)
//      同样反序但恒界内(r>=l>=1,nums[r-1] 摸不到 n),单独未爆——单修
//      分工实证:只修 l 侧全池归零,只修 r 侧原样炸。同一笔误,l 侧必爆
//      r 侧未爆。

class Solution {
public:
    vector<vector<int>> threeSum(vector<int>& nums) {
        int n = nums.size();
        sort(nums.begin(), nums.end());
        vector<vector<int>> res;
        for (int i = 0; i < n - 2; i++)                  // 定一枚锚,剩两枚交给对撞
        {
            if (i > 0 && nums[i] == nums[i - 1])         // i 层去重:块首已配完全场(坑1/坑2)
                continue;
            if (nums[i] > 0)                             // 剪枝:锚为正,三正之和必>0(坑6:不能>=0)
                break;
            int l = i + 1, r = n - 1;                    // l 从 i+1:不复用+定字典序(坑5)
            while (l < r)
            {
                int sum = nums[l] + nums[r];
                if (sum == -nums[i])                     // 167 同款判据:和与目标比大小
                {
                    res.push_back({nums[i], nums[l], nums[r]});
                    while (l < r && nums[l] == nums[l + 1]) l++;  // 命中后跳同值块(坑3:必须命中后)
                    while (l < r && nums[r] == nums[r - 1]) r--;
                    l++; r--;                            // 跳完块还得各走一步(坑4 死循环)
                }
                else if (sum < -nums[i])
                    l++;                                 // 小了:l 出局
                else
                    r--;                                 // 大了:r 出局
            }
        }
        return res;
    }
};

// 解法二(自敲版,2026-11-16 三交 AC;提交时改名 Solution):
//   首交坑9(push_back 三实参编译错)/坑10(if 代 while 块长>=3 重收),二交
//   坑11(守卫站 && 右侧先访后判,ASAN 越界),三交守卫换左一遍过。与参考版
//   逐行同构:排序先行/i 层去重比前一枚/剪枝 >0/l=i+1/方向判据/命中先跳块
//   再走步全同。差异一条(未爆):sum 表达式在 if 与 else-if 判据里各算一遍,
//   同刻数组不变恒同,只多常数(同 0011 坑7 家族)。守卫换左版转写全池
//   (穷举 19500+随机 20000)零分歧零越界。变量与语义保持原提交原貌,
//   仅对齐仓库排版。
class Solution2 {
public:
    vector<vector<int>> threeSum(vector<int>& nums) {
        int n=nums.size();
        vector<vector<int>> res;
        sort(nums.begin(),nums.end());
        for(int i=0;i<n-2;i++)
        {
            if(i>0&&nums[i]==nums[i-1])
            {
                continue;                                       // i 层去重:块首已配完全场(坑1/坑2)
            }
            if(nums[i]>0)
            {
                break;                                          // 剪枝:锚为正三正必>0(坑6)
            }
            int l=i+1,r=n-1;                                    // l 从 i+1:不复用+定字典序(坑5)
            while(l<r)
            {
                if(nums[l]+nums[r]==-nums[i])                   // 判据里算第一遍(未爆常数)
                {
                    res.push_back({nums[i],nums[l],nums[r]});   // 一件货:大括号打包(坑9)
                    while(l<r&&nums[l+1]==nums[l])              // 守卫在左:判先于访(坑11)
                        l++;
                    while(l<r&&nums[r-1]==nums[r])              // r 侧守卫同样在左
                        r--;
                    l++;
                    r--;                                        // 跳完块各走一步(坑4/坑10)
                }
                else if(nums[l]+nums[r]<-nums[i])               // else-if 再算一遍(未爆常数)
                    l++;
                else
                    r--;
            }
        }
        return res;
    }
};
