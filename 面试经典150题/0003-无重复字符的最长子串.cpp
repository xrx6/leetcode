// 链接:https://leetcode.cn/problems/longest-substring-without-repeating-characters/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(滑动窗口求最长镜像:不可行即缩左,吐到可行才收
//   长度;统计量换成窗口字符计数;O(n)/O(|Σ|);自己敲一遍,一遍过
//   AC(2026-11-17)——口述收账,代码未贴回,自敲版未存档)
//
// 思路:
//   题眼三连:「子串(连续)」+「无重复」+「最长」。暴力按左端扩右端
//   O(n^2)(n=1e5 → 1e10)必超。与 209 同一副骨架,方向翻面:求最短
//   「可行即缩」,求最长「不可行即缩」——窗口永远维持无重复,坏了就修
//   到好,修完收长度。统计量从「窗口和」换成「窗口字符计数」cnt[128],
//   进出窗 O(1) 增减。
//   为什么只查 cnt[s[r]] 不用全桶扫:不变量——每轮缩完窗口必无重复,
//   新罪犯只可能是刚进的 s[r];其余字符若有重复,早在它们进门那轮就
//   被修掉了。
//   空串边界:n=0 时 for 不进,ans=0 天然对——求最长的初值 0 兼「空答
//   案」,连哨兵都省了(209 对照:求最短无解才返 0,n 是合法答案,必须
//   n+1 哨兵)。
//   解法二(跳版):不逐件吐,记 last[c]=上次出现位置;案发时 l 直接
//   跳到 last[s[r]]+1(带 last>=l 判据防倒车),吐货改跳案发点。
// 复杂度:
//   解一 O(n):r 合计 n 步,l 合计至多 n 步(均摊账与 209 同款);空间
//   O(|Σ|)=O(128)。解二 O(n)/O(128)。基线:暴力 O(n^2)(按左端扩
//   右端,桶查重)。计数与长度都 <= 1e5,int 无虞。
// 坑:
//   1. 收缩用 if 代 while:重复同伙不在 l 处时缩不干净,窗口带重复照样
//      收长度。标本 abba:r=3 进 a 时 b 的重复还剩一个在窗内,bba 无效
//      窗收了 3,真 2;穷举({a,b}n<=8+{a,b,c}n<=6,1602 例)50.7% 错,
//      随机 51.0%。与 209 坑1 同款笔误(那边漏的是「吐到不可行」,这
//      边漏的是「修到可行」)。
//   2. 先收后缩(收挪到吐前):记到不可行窗,往大错。标本 aa 输出 2
//      真 1;判官示例1 abcabcbb 也错(r=3 先收 abca 的 4 再缩,输出 4
//      真 3);穷举 89.5%,随机 82.8%。收长度的铁律:只在窗口可行的
//      那一刻收——209 的可行在吐之前(先收后吐),这里的可行在吐完
//      之后(先吐后收),方向翻面铁律不变。与 209 坑2 互为镜像(那边
//      先缩后收往小错,这边先收后缩往大错)。
//   3. 判据写 cnt[s[r]]>=1(把「有同伙」写成「出现即破戒」):每件货进
//      门都触发收缩,l 直接追平 r+1,每轮收 0——非空输入穷举池 1602/
//      1602 全错,空串侥幸对。标本 a 输出 0 真 1。破戒线是重复(>1),
//      不是出现。
//   4. 判据查错对象 cnt[s[l]]>1(查要吐的不查新进的):查的是「下一个
//      要吐的字符有没有同伙」,新罪犯 s[r] 的重复没人管。标本 abb:
//      r=2 查到 cnt[a]=1 不缩,abb 无效窗收 3,真 2;穷举 79.4%,随机
//      59.9%。判据要盯「刚进的这件」——不变量保证它是唯一可能的罪犯。
//   5. 吐货忘减计数(只 l++ 不 cnt[s[l]]--):计数只增不减,判据一旦为
//      真永真,l 一路吃穿 n 读 s[n] 越界(ASAN heap-buffer-overflow 家
//      族;Python 转写响亮 IndexError)。穷举 98.8% 炸,最小标本 aa 仅
//      2 格;全不重复的串(从不进 while)侥幸活。计数是统计量的账本,
//      走指针不记账本 = 白走。
//   6. (解二)无条件跳 l=last[s[r]]+1(忘判 last>=l):旧案不在窗内也
//      跳,last=-1 时 l 直接倒回 0。标本 aab:r=2 的 b 没来过,last[b]
//      =-1,l 从 1 倒回 0,aab 无效窗收 3,真 2;穷举 79.4%,随机
//      60.1%。l 的单向性是均摊账的地基,倒一次车账就烂——跳必须带防
//      倒车判据(或写 max(l,last+1))。
//   7. (语言层,未爆)cnt[s[r]] 拿 char 当数组下标:题面「英文字母、数
//      字、符号和空格」=可打印 ASCII(<128),signed char 非负,安全
//      是题面兜的;UTF-8/原始字节 >=0x80 经 signed char 成负数,负下标
//      静默 UB(125 cctype 同宗,先过 (unsigned char) 闸)。

// 解法一(滑动窗口,桶计数逐件吐,主解)
class Solution {
public:
    int lengthOfLongestSubstring(string s) {
        int n = s.size();
        int cnt[128] = {0};                               // 窗口字符计数(统计量)
        int ans = 0;                                      // 求最长:0 兼空串答案,哨兵免了
        for (int r = 0, l = 0; r < n; r++)
        {
            cnt[s[r]]++;                                  // r 进货
            while (cnt[s[r]] > 1)                         // 不可行:新货有同伙,修到可行(坑1:while)
            {
                cnt[s[l]]--;                              // l 吐货,账本同步减(坑5)
                l++;
            }
            ans = max(ans, r - l + 1);                    // 吐完必可行,此刻收(坑2:收在吐后)
        }
        return ans;
    }
};

// 解法二(跳版:上次出现位置,案发跳转;提交时改名 Solution):
//   last[c]=上次出现下标;旧案在窗内(last>=l)才跳 l=last+1,防倒车
//   (坑6)。与解一在全池(穷举 1602+随机 20000)逐例一致。
class Solution2 {
public:
    int lengthOfLongestSubstring(string s) {
        int n = s.size();
        int last[128];
        fill(last, last + 128, -1);                       // -1=没来过
        int ans = 0;
        for (int r = 0, l = 0; r < n; r++)
        {
            if (last[s[r]] >= l)                          // 旧案在窗内:跳到案发点+1(坑6:防倒车)
                l = last[s[r]] + 1;
            last[s[r]] = r;                               // 结案登记
            ans = max(ans, r - l + 1);
        }
        return ans;
    }
};
