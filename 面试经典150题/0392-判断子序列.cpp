// 状态:独立完成(2026-11-03,双指针顺序匹配一遍过 AC;坑1 空 s 守卫实为救命,
//       坑2 m>n 守卫纯提速;进阶 k≥1e9 的解法二跳表、解法三二分由讲解补入);
//       三解逐行转写 Python 穷举 148318+官方 2+随机 20000+大串 500+构造正 2988
//       负 3000 全对(合计 174808 对,dp/迭代器双基线互证零分歧)
//
// 思路:
//   子序列=「可跳字」的匹配:t 可以不理 s 不需要的字符。所以不需要 28 那套
//   失配回退——t 的字符要么正好是 s 在等的(配上,s 指针前进),要么跳过,
//   永不回头。两根指针各管一串:i 单向扫 t(驱动),j 等在 s(只进不退)。
//   这是双指针第四姿势:前三姿势(同向压实/相向配对/逆向倒写)两根指针
//   在同一串上,这里各管一串。贪心:每个 s 字符配 t 中「当前位置之后最早的
//   出现」——交换论证不逼死:若存在任一嵌入 i1<i2<…,贪心嵌入逐位 ≤ 它,
//   每步只会更早配上、余量更多(与 134 留余量的贪心直觉同源)。
//   进阶(k≥1e9 个 s 查同一个 t):解法一每查 O(n) 扫一遍 t,t 固定时这遍
//   扫描是纯重复(1e9×1e4=1e13 次比较)。把「从位置 i 起字符 c 下次在哪」
//   预处理成跳表 nxt(序列自动机),查询沿 s 纯查表,单查 O(m)≤100,
//   t 再也不扫——压表族(与 28 π 表、12 罗马面额表同宗:运行期决策提到
//   预处理期一次算清)。变体解法三:每字母位置表+二分,省 26 倍表换 log。
//   与 28 的分野一句话:子串不能跳字,失配要回退(π 表);子序列能跳字,
//   失配即前进——贪心就够,永不需要 π(另册 notes/双指针/顺序匹配.md)。
// 复杂度:
//   解法一 O(n+m)/O(1)(n=1e4 主导)。
//   解法二(进阶)预处理 O(26n)/O(26n)(≈2.6e5 个 int,约 1MB),单查 O(m)。
//   解法三(进阶变体)预处理 O(n)/O(n),单查 O(m log n)。
//   基线:O(nm) DP(经典判子序列,1e6 放行);暴力枚举 t 子序列 2^n 不可行。
//   进阶账:k=1e9 次查询,解法一 1e13 次比较死;解法二预处理只付一次,
//   每查 O(m)=1e11,且「读 s」本身就是单查下界,已到底。
// 坑:
//   1. 空 s 守卫是救命的,不是装饰(必爆):无守卫版 (s="",t="") 循环不进
//      → 返 false,真答 true(转写实证:池内 36 例同形对全错,失败集恰为
//      s、t 皆空)。而 (s="",t="x") 侥幸对——空串 s[0] 有定义返回 '\0'
//      (C++11 起 pos==size() 特权位,再多越一位才 UB;vector 同位是 UB,
//      string/vector 一家亲的反例,语言参考·空 vector 下标节)。解法二/三
//      空 s 循环不进天然返真,无需守卫——守卫要不要看骨架,不看成例。
//   2. m>n 提前返假:纯提速非必要(未爆)。无它仍对——j 至多被配 n 次,
//      n<m 时 j 永远到不了 m,s[j] 越界读都不会发生,只是白扫一整串
//      (转写实证:失败集=空)。
//   3. (解二)忘 pos++:同一位置被相邻同字符反复白嫖,最小反例 s="aa"/
//      t="a" 误真(转写实证:穷举+随机池 36124 错,全部误真方向)。
//   4. (解二)建表顺序:先整行抄 nxt[i+1],再盖 nxt[i][t[i]]=i;反了自盖
//      被整行抄掉,表里丢掉 i 号位自己,最小反例 s="a"/t="a" 误假。哨兵 n
//      语义=「没有」,查询判 pos==n 要在 pos++ 之前(哨兵位本身不是答案)。
//   5. 排查备注(非坑):int m=s.size() 直收,无 -1 表达式,无 125 坑6 的
//      无符号回绕面;j==m 判在配对后同轮查——无守卫且 m=0 时正是靠这条
//      0==0 即真,但它救不了 (空,空)(坑1):循环根本不进。

// 解法一(双指针顺序匹配,独立完成 2026-11-03 一遍过 AC,主解):i 扫 t、j 等在 s,
//   配上 j 才前进;贪心最早匹配,交换论证不逼死。变量与结构保持原提交原貌,仅对齐排版。
class Solution {
public:
    bool isSubsequence(string s, string t) {
        int m=s.size();                           // 直收 int:无 -1 表达式,无回绕面(坑5)
        int n=t.size();
        if(m==0)
            return true;                          // 空 s 恒真;守卫必要——无它 (空,空) 返假(坑1)
        if(m>n)
            return false;                         // 纯提速非必要:无它仍对(坑2)
        for(int j=0,i=0;i<n;i++)                  // i 单向扫 t(驱动),j 等在 s(只进不退)
        {
            if(s[j]==t[i])                        // 正好是 j 在等的字符:配
                j++;                              // j 前进一格:贪心最早匹配
            if(j==m)
                return true;                      // s 全配完即真,早退
        }
        return false;                             // t 扫完还没配完:后面没有字符可配了
    }
};

// 解法二(进阶,k≥1e9 个 s 查同一个 t;跳表/序列自动机;提交时改名 Solution):
//   预处理:从右往左一行递推 nxt[i][c]=从 i 起(含 i)字符 c 的首次出现,
//   哨兵 n=「没有」;查询:沿 s 纯查表,单查 O(m),t 再也不扫。
//   注意:LeetCode 单查接口下表每查重建 O(26n),单查反而不如解法一——它的
//   主场是海量查询:表建一次缓存住(如按 t 内容做静态缓存),预处理只付
//   一次,吃 k 次查询。
class Solution2 {
public:
    bool isSubsequence(string s, string t) {
        int n=t.size();
        vector<array<int,26>> nxt(n+1);           // nxt[i][c]:从 i 起 c 的首现;行 n=哨兵
        nxt[n].fill(n);                           // 哨兵 n=「没有」(坑4)
        for(int i=n-1;i>=0;i--)
        {
            nxt[i]=nxt[i+1];                      // 先整行抄右边(坑4:反了自盖被抄掉)
            nxt[i][t[i]-'a']=i;                   // 再盖自己:i 处正是自己的最早
        }
        int pos=0;                                // 下一个配对必须落在 pos 之后
        for(char c:s)
        {
            pos=nxt[pos][c-'a'];                  // 一步跳到 c 的首现:扫描变跳转
            if(pos==n)                            // 哨兵=后面没有 c 了(坑4:判在 ++ 前)
                return false;
            pos++;                                // 下个字符严格在其后(坑3:漏了同位白嫖)
        }
        return true;                              // 空 s 循环不进天然真,无需守卫(对照坑1)
    }
};

// 解法三(进阶变体,每字母位置表+二分;提交时改名 Solution):
//   预处理只 O(n):每字母一张升序出现下标表;查询 lower_bound 找「≥ 上次
//   配对位+1」的最早出现,单查 O(m log n)、内存 O(n)——拿 log 换 26 倍表。
//   贪心与解法一同款,只是「找下一个 c」从扫(解一)、跳(解二)换成二分。
class Solution3 {
public:
    bool isSubsequence(string s, string t) {
        int n=t.size();
        vector<vector<int>> pos(26);              // 每字母的升序出现下标表
        for(int i=0;i<n;i++)
            pos[t[i]-'a'].push_back(i);
        int start=0;                              // 下一配对下标须 >= start(=上次+1)
        for(char c:s)
        {
            vector<int>& v=pos[c-'a'];
            auto it=lower_bound(v.begin(),v.end(),start);   // 首个 >= start 的出现
            if(it==v.end())                       // 该字母没有够靠后的出现了
                return false;
            start=*it+1;
        }
        return true;
    }
};
