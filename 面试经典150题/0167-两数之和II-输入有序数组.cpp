// 解法一(相向双指针对撞搜索,主解):125 的骨架,判据从「相等/不等」
//   升级成「与 target 比大小给方向」。
class Solution {
public:
    vector<int> twoSum(vector<int>& numbers, int target) {
        int l=0, r=numbers.size()-1;              // 首尾各一枚;答案对恒在 [l,r]
        while(l<r)                                 // l==r 同一格不许自配;循环内必 return
        {
            int sum=numbers[l]+numbers[r];
            if(sum==target)
                return {l+1, r+1};                 // 下标 1 起(坑4);找到即返免标志位(坑1③)
            else if(sum>target)
                r--;                               // 大了:r 凑不出,整列出局(坑2:别动 l)
            else
                l++;                               // 小了:对称,l 出局
        }
        return {-1,-1};                            // 题面保证唯一解,走不到(诚实兜底)
    }
};

// 解法二(定一枚+右段二分,O(n log n)/O(1)):对每枚 i,只在 (i,n) 里
//   二分找 target-numbers[i](坑3:全数组找会在 x+x==target 时找到自己)。
class Solution2 {
public:
    vector<int> twoSum(vector<int>& numbers, int target) {
        int n=numbers.size();
        for(int i=0;i<n;i++)
        {
            int need=target-numbers[i];            // 要找的搭档值
            int lo=i+1, hi=n-1;                    // 只在右段找:排除自己(坑3)
            while(lo<=hi)
            {
                int mid=lo+(hi-lo)/2;
                if(numbers[mid]==need)
                    return {i+1, mid+1};           // 唯一解保证命中即正主
                else if(numbers[mid]<need)
                    lo=mid+1;
                else
                    hi=mid-1;
            }
        }
        return {-1,-1};
    }
};
