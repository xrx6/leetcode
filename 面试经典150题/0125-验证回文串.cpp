// 思路:
//   回文=首尾对称位置逐一配对。顺序扫描要回头,配对不必:首尾各一枚指针
//   向中间走,失配即假,相遇即真。两件事污染配对:
//   ① 非字母数字不参与——指针撞上就原地跳过(各自跳各自的);
//   ② 大小写算同一字符——比较前 tolower 归一。
//   全程在原串上做,不开新串 ⇒ O(1) 空间。空串/全干扰串两枚指针擦肩而过、
//   一次比较都没发生 ⇒ 天然 true(示例3),不用特判。
//   解法二换分工:把「跳过+归一」前置——快慢指针原地压实(27/151 老骨架
//   换芯:收的条件=isalnum,写入多了层变换 tolower 归一抄),压出的有效
//   前缀 [0,slow) 再做半程对撞。一题串双册:相向双指针(新)+快慢指针
//   (旧骨架新用法)。l、r 各自单调不回头,又是「无后效」家族——14 候选
//   只缩不涨、238 滚动乘同族。
// 复杂度:
//   解法一 O(n)/O(1):l 只增 r 只减,合计移动 ≤ n,每格至多左右各碰一次。
//   解法二两趟 O(n)/O(1)(参数本就是按值副本,原地写它不开新空间)。
//   基线:滤新串+整串翻转比较 O(n)/O(n),最直观但白开一倍空间
//   (翻转视角回看 notes/翻转/三次翻转.md)。
// 坑:
//   1. isalpha 误替 isalnum:字母和数字都是「字母数字字符」,滤芯只留字母
//      会把数字丢掉。最小反例 "0P"(判官经典用例):丢 '0' 剩 "P" 自翻自
//      误判 true,真答 false;穷举池 265 例错 61(凡数字参与首尾配对的
//      串全 WA)。反向冗余版跳过条件 !isalpha&&!isdigit 不算错——
//      isalnum 就是它俩的或。
//   2. 不归大小写直接比原字符:'A'!='a'。最小反例 "aA":真答 true 判
//      false(穷举池 265 例错 24)。归一两边都要做,比时归一还是抄时归一
//      只是搬位置;顺带 tolower 对非字母原样返回('0'→'0'),不必写
//      「是字母才 lower」的分支。
//   3. 内层跳过缺 l<r 守卫:左跳能一路跑出串尾、右跳能跑成 r=-1,随后
//      s[l]/s[r] 越界读——C++ operator[] 不检查,静默 UB。最小反例 "!!";
//      逐行转写 Python 响亮 IndexError 对照 C++ 无声越界读,与 0028 π 表
//      开小同族:那边越界写、这边越界读。只守卫一侧不行,另一侧照越界:
//      右跳无守卫在 ",!" 上 r 成负下标,Python 先悄悄绕回串尾错位、再往下
//      才 IndexError,C++ 则 r=-1 那一刻已是 s[-1] 越界读。
//   4. 跳完不再判 l<r 直接比(未爆,安全):守卫跳过后恒有 l<=r(左跳最多
//      停在与 r 相等处,右跳不会低于 l),l==r 时同一格自己比自己必等。
//      注意先后:是坑3的守卫保证了这里的安全,不是比较处的 if 救了坑3。
//   5. (未爆,语言层)isalnum/tolower 参数类型是 int,标准要求值域为
//      unsigned char 或 EOF:传负 char 是 UB。本题约束「可打印 ASCII」
//      (0x20~0x7E 恒非负)兜住;迁移到字节流/扩展字符(UTF-8 >=0x80 的
//      字节经 signed char 成负数)必雷。稳妥写法 (unsigned char)s[l]。

// 解法一(相向双指针,主解):首尾对撞,跳过干扰→归一→配对,全程原地。
class Solution {
public:
    bool isPalindrome(string s) {
        int n=s.size(), l=0, r=n-1;                  // 首尾各一枚,相向而行
        while(l<r)
        {
            while(l<r&&!isalnum(s[l]))               // 左跳干扰:守卫在前(坑3)
                l++;
            while(l<r&&!isalnum(s[r]))               // 右跳干扰:同一条守卫
                r--;
            if(tolower(s[l])!=tolower(s[r]))         // 两侧都归一再比(坑2;坑4:此处恒 l<=r)
                return false;
            l++;                                     // 这对配成,各进一格
            r--;
        }
        return true;                                 // 全程无失配:空串/全干扰/真回文都落这里(示例3)
    }
};

// 解法二(快慢指针压实+半程对撞,提交时改名 Solution):
//   「跳过+归一」前置成滤芯:27 的骨架换两处芯——收的条件从「!=val」
//   换成 isalnum,写入从原样抄换成 tolower 归一抄(slow<=fast 不变量
//   原样成立,写的都在 fast 脚印后面)。压完 [0,slow) 是纯化小写串,
//   对撞只走半程。151 压完要 resize 砍尾是因为它要交整串,这边不交串:
//   比较循环认 slow 不认 size(),那一刀天然免掉——要不要砍尾跟着
//   「交不交串」走,不跟压实走。
class Solution2 {
public:
    bool isPalindrome(string s) {
        int slow=0;
        for(int fast=0; fast<(int)s.size(); fast++)
            if(isalnum(s[fast]))
                s[slow++]=tolower(s[fast]);          // 滤芯:字母数字才收,收时顺手归一(坑1/坑2)
        int l=0, r=slow-1;                           // 有效前缀 [0,slow),后面是废数据
        while(l<r)
        {
            if(s[l]!=s[r])                           // 已归一,直接比
                return false;
            l++;
            r--;
        }
        return true;
    }
};
