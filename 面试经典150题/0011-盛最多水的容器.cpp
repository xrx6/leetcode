// 题号:0011  题名:盛最多水的容器  难度:中等
// 链接:https://leetcode.cn/problems/container-with-most-water/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(相向双指针对撞求最值:面积=短板×间距,每步只淘汰短板,
//   O(n)/O(1);待自己敲一遍 AC)
//
// 思路:
//   面积 = min(height[l], height[r]) × (r-l):水位由矮板(短板)决定,间距是
//   宽度。暴力每对都量 O(n^2),n=1e5 即约 5e9 次配对,必超。题眼是「短板
//   决定水位」:首尾各一枚指针,先用当前窗口更新答案;然后只移动短板——
//   设 height[l] < height[r],把 l 留住、r 往左收的任何一对 (l,r') 面积
//   = min(height[l],height[r']) × (r'-l) ≤ height[l] × (r-l) = 当前面积,
//   即短板 l 配窗口内任何板都超不过当前,它不可能出现在更优解里,l++ 出局
//   不亏。长板则不然:它可能等到更高的新板把水位抬起来([1,5,100] 里留住
//   100 等到 5,5×1=5 > 1×2=2),所以绝不能收长板。窗口每步至少废一枚
//   端点,合计 ≤ n-1 步,ans 已记下所有被淘汰者能贡献的最好成绩。
//   对撞的第三种任务:125 验证(失配即判假,走满窗口)、167 搜索(判据带
//   方向,失配淘汰一侧,循环内必 return)、本题求最值(每步更新 ans 再淘汰
//   必输的一侧,窗口走空自然收场,不 return)。
//   与 42 的关系:42 的双指针版也移动较矮的一侧(盆沿瓶颈),动作同;但
//   42 淘汰的是「矮侧盆沿已定」,本题淘汰的是「短板配谁都超不过当前」,
//   论证各表。42 的前缀/后缀最大解法见 0042 与双向扫描册。
// 复杂度:
//   时间 O(n):l 只增 r 只减,合计移动 ≤ n-1 步,每步一次 min/乘法;
//   空间 O(1)。基线:暴力枚举所有对 O(n^2)/O(1)(n=1e5 约 5e9 次,必超)。
//   int 够用:n ≤ 1e5、height[i] ≤ 1e4,最大面积 1e9 < INT_MAX(约 2.1e9);
//   题面量级再放大就要 long long。
// 坑:
//   1. 水位是短板:面积 = min(height[l],height[r]) × (r-l),不是 max、更
//      不是单边。取 max 版在 [1,2] 得 2(真值 1),穷举池(长度 2..6、
//      高度 0..3,长度≥3 子池 5440 例)错 4753,87.4% 必爆级;恒取左
//      height[l] 在 [2,1] 得 2(真值 1),池错 2624(48.2%);恒取右
//      height[r] 在 [1,2] 得 2(真值 1),池错 3229(59.4%)。
//   2. 移动方向:淘汰短板,不是长板。最小正数反例 [1,3,3]:真值 3(下标
//      1,2 的 3×1),移长板版第一步把右 3 收掉,只拿 1×2=2 收场;更醒目的
//      [1,5,100]:真值 5(内对 5×1),错版 2;判官示例 [1,8,6,2,5,4,8,3,7]
//      真值 49,移长板版只有 8。穷举池移长板错 3544/5440(65.1%),必爆级。
//      道理:宽度只会变小,收长板时水位 min 仍 ≤ 当前短板,面积只会小;
//      只有收短板才可能让水位往上跳。与 167「方向移反」同族:淘汰错了对象。
//   3. 宽度是下标差 r-l,不是点数 r-l+1。[1,1] 真值 1,+1 版得 2;穷举池
//      +1 版错 5382/5440(98.9%),全场最离谱的必爆项。间距是「隔了几格」,
//      不是「数了几根」。
//   4. 不能每轮两指针都收:丢的是「换搭档」的中间态 (l,r-1)/(l+1,r)。
//      [1,2,3,4] 真值 4(下标 1,3 的 2×2),双收版只拿 3;判官示例双收版
//      24≪49。穷举池双收版错 3052/5440(56.1%)。
//   5. 等号时收哪边都安全,同时收也安全(未爆,穷举池 0 错):h[l]==h[r]
//      时两侧都是短板,含 l 或 r 的对面积 ≤ min×宽度 = 当前,同时出局不丢
//      任何更优对。标准写法 if(h[l]<h[r]) l++ else r-- 在等号时收右,只是
//      保守省事。
//   6. 守卫与自配(未爆):while(l<=r) 时 l==r 自配面积为 min×0 = 0,白算
//      一次不改答案。与 167 的 l==r 自配必爆对照:那边自配=同一元素用两次
//      违反题面,这边宽度 0 天然无害。写 l<r 只是省一次空转,不是正确性
//      护栏——同一处守卫,题意不同,判罚两样。

class Solution {
public:
    int maxArea(vector<int>& height) {
        int n = height.size();
        int l = 0, r = n - 1, ans = 0;
        while (l < r)
        {
            ans = max(ans, min(height[l], height[r]) * (r - l));  // 面积=短板×间距(坑1/坑3)
            if (height[l] < height[r])
                l++;                                               // 短板出局:它配谁都超不过当前(坑2)
            else
                r--;                                               // 等号收右也安全,两边都是短板(坑5)
        }
        return ans;                                                // 窗口走空,ans 即最优
    }
};
