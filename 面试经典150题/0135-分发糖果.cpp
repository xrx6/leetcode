// 题号:0135  题名:分发糖果  难度:困难
// 链接:https://leetcode.cn/problems/candy/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(自己先试:数相邻不等对,两示例巧合通过,[1,2,3] 反例 5≠6;待自己敲一遍 AC)
//
// 思路:
//   规则翻译成边约束:每个孩子 ≥1;每对相邻 (i-1,i) 中评分更高的糖果严格
//   更多。注意相等评分不产生任何约束(示例2 [1,2,2] → 1,2,1,第三个孩子
//   拿 1 颗不违规)。糖果数不由「赢了几次比较」决定,由「在链上的位置」
//   决定:candy[i] 至少是以 i 结尾的严格上升链长度 left[i](链头 1,链上
//   每步被迫 +1,链式传递);同理至少是以 i 开头的严格下降链长度 right[i]。
//   两张下界证书夹住每个点:任何可行方案都有 candy[i] ≥ max(left,right),
//   而取等号的方案恰好可行(见坑3)→ 逐点最小 → 总和最小。
//   left/right 各是一条一维链 DP:正着扫一遍、倒着扫一遍,就地取 max
//   合并,再求和。为什么必须两趟:上升信息从左边传来,下降信息从右边
//   传来,谷底的孩子要同时听两边的话——不像 134 的 total 能边扫边同步
//   累加,这里两侧合并的是 max,另一半信息装不进一个变量,只好各扫各的。
// 复杂度:
//   时间 O(n)  空间 O(n)(存在 O(1) 空间的升/降段计数变体,进阶方向)
// 坑:
//   1. 原解错因标本:count = n + Σ[相邻不等]。①丢方向:[1,3,2] 算 5、
//      正解 4,下降对(i 比 i-1 低)不该加;②丢链长:[1,2,3] 算 5、正解
//      6,同向连赢是链式累加(1,2,3),不是每次 +1。两个给定示例恰是
//      谷形/单升长度2,每处不等恰差一颗,巧合掩盖了结构。另:条件里
//      ratings[i]!=ratings[i-1] 与 ratings[i-1]!=ratings[i] 互为反写,
//      A||A 恒等于 A。
//   2. 触发条件是「严格更高」,不是「不相等」:相等两边给一样多(甚至
//      都给 1)完全合法,别脑补成「不同就得多给」。
//   3. 第二趟用 max 不用覆盖:倒扫更新 candy[i] 时它已背着左约束,取
//      max 才两边都满足。可行性细账:边 (i-1,i) 上 ratings[i] 更高时,
//      败者 i-1 在右扫的判断(ratings[i-1]>ratings[i])直接出局,右链
//      值必为 1 → candy[i-1]=left[i-1],而 candy[i] ≥ left[i-1]+1,
//      严格胜出。两趟各管半边,从不打架。
//   4. 数值口径:最坏情况严格递增,总和 = n(n+1)/2 ≈ 1.25e9 <
//      INT_MAX ≈ 2.1e9,int 撑得住;n 再大一档就得 long long。
//   5. 边界自动安全:n=1 时两趟循环都不进,返回 candy[0]=1;第二趟
//      从 n-2 起步,i+1 最大到 n-1,不越界。

class Solution {
public:
    int candy(vector<int>& ratings) {
        int n = ratings.size();
        vector<int> candy(n, 1);              // 规则①:每人至少 1 颗
        for (int i = 1; i < n; i++)           // 左→右:只看左边,candy[i]=左链长
            if (ratings[i] > ratings[i - 1])
                candy[i] = candy[i - 1] + 1;
        for (int i = n - 2; i >= 0; i--)      // 右→左:只看右边,合并取 max
            if (ratings[i] > ratings[i + 1])
                candy[i] = max(candy[i], candy[i + 1] + 1);
        int total = 0;
        for (int c : candy)
            total += c;
        return total;
    }
};
