// 题号:0122  题名:买卖股票的最佳时机II  难度:中等
// 链接:https://leetcode.cn/problems/best-time-to-buy-and-sell-stock-ii/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(贪心思路由分层提示推出;官方 DP 题解自己敲一遍 AC)
//
// 思路:
//   121 限一次交易,按"卖出日"分类就够;122 交易次数不定,没法按交易分类,
//   改按"天"分类:每天收盘只有「持股/不持股」两种状态,转移只有「延续/买/卖」
//   三种。dp[i][0]=第 i 天收盘不持股的最大利润;dp[i][1]=持有一股(买入价已扣)。
//   答案取 dp[n-1][0]:最后一天还持股的话,那股的钱扣了没赚回,最后一天卖掉
//   (当天买卖也行)不会更差,最优必落在不持股。
// 复杂度:
//   时间 O(n)  空间 O(n) ← 只依赖前一天,可滚动成两个变量 O(1)
// 坑:
//   1. dp[i][1] 用的是 dp[i-1][0](旧值)——数组版按下标天然取旧值;压成滚动
//      变量后两个新值必须都从旧值算,要临时变量存住,否则"今天卖完今天买"
//      的转移就串了(本题恰好无害,123/188 加维度后必错)。
//   2. int dp[n][2] 是 VLA(C99 特性,非标准 C++):LeetCode 的 GCC 当扩展放行,
//      MSVC 直接编译错;真正的雷是栈——默认 1~8MB,n 大了直接爆且无法捕获。
//      标准写法 vector<vector<int>> dp(n, vector<int>(2)); 或滚动两个 int。
//   3. 同一天买卖利润为 0,不影响最优值,两个模型都无需特判。
// 进阶:
//   贪心:答案 = Σ max(0, prices[i]-prices[i-1])——任意交易的利润可拆成相邻
//   日差之和,正差全收、负差(不持股)跨过;它正是本 DP 每天的增量,即贪心是
//   这台状态机在"不限次"下的坍缩特例,三行核心。123/188(限 k 次)给状态加
//   "已交易次数"维 dp[i][j][0/1] 机器不变;309 冷冻期、714 手续费同理。
class Solution {
public:
    int maxProfit(vector<int>& prices) {
        int n = prices.size();
        int dp[n][2];
        dp[0][0] = 0; dp[0][1] = -prices[0];
        for (int i = 1; i < n; i++)
        {
            dp[i][0] = max(dp[i-1][0], dp[i-1][1] + prices[i]);
            dp[i][1] = max(dp[i-1][1], dp[i-1][0] - prices[i]);
        }
        return dp[n-1][0];
    }
};
