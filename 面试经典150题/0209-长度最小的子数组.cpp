// 题号:0209  题名:长度最小的子数组  难度:中等
// 链接:https://leetcode.cn/problems/minimum-size-subarray-sum/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(正数给单调性,右端进货、可行即左端吐货,吐一步收一步
//   长度——同向双指针压「窗口统计量」;O(n)/O(1);自己敲一遍,一遍过
//   AC(2026-11-16)——自敲版以 Solution2 与参考版并存,与参考版零语义
//   级差异:右端叫 i、三声明并一行,判据/次序/哨兵/终检全同)
//
// 思路:
//   题眼三连:「正整数数组」+「连续子数组和 >= target」+「最短」。暴力枚举
//   双端 O(n^2)(n=1e5 → 1e10)必超。降元靠正数送的单调性:固定右端 r,
//   左端越左和越大 ⇒ 每个 r 存在「最短可行左端」L(r);r 右移时窗口只肥
//   不瘦,L(r) 只会右移——两根指针各自单程、都不回头,合计至多 2n 步。
//   这就是滑动窗口:与快慢指针同为同向双指针,那边压「元素」(原地写),
//   这边压「统计量」(窗口和 sum,一个变量随进出窗 O(1) 增减,窗内不再
//   重算)。
//   骨架三行:r 进货 sum+=nums[r];可行(sum>=target)就收长度 r-l+1、
//   l 吐货 sum-=nums[l++],吐到不可行为止。
//   为什么对:每个 r 都把 l 送到「以 r 为右端的最短可行左端」;最优解必
//   以某个 r 为右端 ⇒ 必被收进 ans,一遍扫全收齐。
//   进阶 O(n log n)(解法二):前缀和把「区间和 >= target」坍缩成两数比
//   较 pre[j] >= pre[i]+target(167 同宗:有序数组两数比大小);全正 ⇒
//   pre 严格递增 ⇒ 二分合法。本题里它比 O(n) 慢,练的是「前缀和+二分」
//   件套——正数一丢(题目允许负数),滑窗的方向性地基整体塌掉,这类题
//   就得靠前缀和接(862 同族)。
// 复杂度:
//   解一(滑窗):时间 O(n)——r 合计 n 步,l 合计至多 n 步,每元素进窗
//   一次出窗一次(均摊账与快慢指针同款);空间 O(1)。解二(前缀和+
//   二分):O(n log n)/O(n)。基线:暴力 O(n^2) 必超。int 账:解一 sum
//   <= 1e5*1e4=1e9 < INT_MAX;解二判据右端 pre[i]+target 最大 2e9,贴
//   INT_MAX(约 2.147e9)的线只剩 7%,量级再抬一点就静默溢出(坑8)。
// 坑:
//   1. 收缩用 if 代 while:每个 r 至多吐一格,同一右端的货吐不完,记到的
//      都偏长。判官示例1 [2,3,1,2,4,3]/7 输出 4,真 2([4,3])——判官示例
//      自己就是标本;最小标本 t=2 a=[1,2] 仅 2 格(r=1 收长度 2 吐掉 1
//      就走人,[2] 没机会收)。穷举(n<=7 值{1,2,3})21.5% 错,随机 45.2%。
//      错法方向:往大里错(该吐没吐完)。
//   2. 先缩后收长度:ans 记到「已不可行」的窗上,吐过头也记。判官示例1
//      输出 1(r=5 吐成空窗 [ ] 剩 0<7 也记了 r-l+1=1),真 2;最小标本
//      t=1 a=[1] 输出 0——连「无解=0」的语义都被冒名。穷举 63.4%,近和
//      随机池 80.2%。错法方向:往小里错。与坑1 同一标本一上一下,次序
//      铁律:先收长度再吐货——收的是「当前还可行」的窗。
//   3. 判据丢等号(sum>target):恰好压线的窗全错过。判官示例2 [1,4,4]/4
//      输出 2,真 1([4] 恰好 4);示例1 也错([4,3] 恰好 7,输出 3)。最小
//      标本 t=1 a=[1](1>1 不成立,唯一窗错过输出 0)。穷举 31.7%,压线
//      浓度高的近和池 64.0%。判据照抄题面:>= 就是 >=。
//   4. 无解哨兵:ans 初值 n+1,收尾 ans>n?0:ans。n 不能当哨兵:n 本身是
//      合法答案——全数组恰好凑够时最优就是 n(标本 [1,1,1,1]/4 → 4)。
//      拿 n 当哨兵或忘终检,无解时输出 n/n+1(判官示例3 [1]*8/11 → 8);
//      失败集恰=无解用例:无解子池 100% 错,有解 0 错。哨兵要和一切合法
//      值区分开:大一号。
//   5. (解二)前缀和数组开 n+1 且 pre[0]=0(空前缀):窗口 nums[i..j-1]
//      的和 = pre[j]-pre[i],长度 = j-i——下标全在 pre 的格上走,原数组
//      一个下标都不用碰。忘掉空前缀那格,「从 0 开头的窗」全体失踪。
//   6. (解二,未爆)二分从 i+1 起(排除空窗)是紧界,从 i 起恰好无害:
//      target>=1>0 ⇒ pre[i]+target>pre[i] ⇒ 落点必 >=i+1,空窗被严格递
//      增顺手排除。全池(穷举 67251+随机 40000)0 差。「松而安全」要有
//      论证不是白给(15 坑8 同宗)。
//   7. (解二)upper_bound 代 lower_bound:一个是「第一个 >」,一个是
//      「第一个 >=」,恰好相等的命中被 > 放走。判官示例1 的最优 [4,3]
//      恰和 7,upper 版收成 3,真 2;最小标本 t=1 a=[1](pre=[0,1],找 >
//      1 落空输出 0)。穷举 31.7%。判据带 >= 配 lower_bound,带 > 才配
//      upper_bound。
//   8. (解二,int 贴线账)pre[i] <= 1e9、target <= 1e9 各自安好,判据右
//      端 pre[i]+target 最大 2e9,离 INT_MAX 只剩 7%——侥幸够,量级抬
//      半档就静默溢出成负数。两端各在 int 内,相加未必在(45 的 INT_MAX
//      加法家族):比较前先算量级账,贴线就整体升 long long。

// 解法一(滑动窗口,参考版,主解)
class Solution {
public:
    int minSubArrayLen(int target, vector<int>& nums) {
        int n = nums.size();
        int ans = n + 1;                                // 哨兵大一号:n 是合法答案(坑4)
        int sum = 0;                                    // 窗口统计量:进出窗 O(1) 增减
        for (int r = 0, l = 0; r < n; r++)              // r 进货,只往右
        {
            sum += nums[r];
            while (sum >= target)                       // 可行才收:判据带等号(坑3)
            {
                ans = min(ans, r - l + 1);              // 先收长度:此刻窗还可行(坑2)
                sum -= nums[l++];                       // 再吐货:while 不是 if(坑1)
            }
        }
        return ans > n ? 0 : ans;                       // 无解收尾(坑4)
    }
};

// 自敲版(看题解后照解法一敲出,2026-11-16 一遍过 AC):与参考版逐行同构,
//   零语义级差异——右端叫 i(参考版叫 r),sum/ans/l 三声明并一行;判据
//   带等号/先收长度再吐货/哨兵 n+1/return 终检全同,坑1-4 家族全避开。
//   转写版全池(穷举 67251+随机 40000)零错。提交时改名 Solution:
class Solution2 {
public:
    int minSubArrayLen(int target, vector<int>& nums) {
        int n=nums.size();
        int sum=0,ans=n+1,l=0;                           // 哨兵大一号(坑4)
        for(int i=0;i<n;i++)                             // i 当右端,只往右
        {
            sum+=nums[i];                                // 进货
            while(sum>=target)                           // 判据读窗口和,带等号(坑3)
            {
                ans=min(ans,i-l+1);                      // 先收长度(坑2)
                sum-=nums[l++];                          // 再吐货,while 不是 if(坑1)
            }
        }
        return ans>n?0:ans;                              // 无解收尾(坑4)
    }
};

// 解法二(进阶 O(n log n):前缀和+二分;提交时改名 Solution):
//   pre 严格递增(全正),对每个 i 二分最小 j 使 pre[j] >= pre[i]+target,
//   窗口 nums[i..j-1] 长度 j-i。与解一在全池(穷举 67251+随机 40000)逐例一致。
class Solution3 {
public:
    int minSubArrayLen(int target, vector<int>& nums) {
        int n = nums.size();
        vector<int> pre(n + 1, 0);                      // pre[0]=0 空前缀(坑5)
        for (int i = 0; i < n; i++)
            pre[i + 1] = pre[i] + nums[i];              // 全正 => 严格递增,二分的地基
        int ans = n + 1;                                // 哨兵大一号(坑4 同款)
        for (int i = 0; i < n; i++)
        {
            int need = pre[i] + target;                 // 最大 2e9,贴 INT_MAX 的线(坑8)
            int j = lower_bound(pre.begin() + i + 1, pre.end(), need) - pre.begin();
            if (j <= n)                                 // 找不到时 lower_bound 给 n+1,不收
                ans = min(ans, j - i);                  // 第一个 >= :恰等命中要收(坑7)
        }
        return ans > n ? 0 : ans;
    }
};
