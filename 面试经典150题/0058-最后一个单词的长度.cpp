// 题号:0058  题名:最后一个单词的长度  难度:简单
// 链接:https://leetcode.cn/problems/length-of-last-word/?envType=study-plan-v2&envId=top-interview-150
// 状态:独立完成(自己先试,随机交叉验证全对;坑2 悬空 c++ 恰好无害,坑3 l/c 冗余)
//
// 思路:
//   问「最后一个」单词 ⇒ 信息住在串尾 ⇒ 从右往左扫,起点就在答案门口。
//   两段式:先跳过尾部空格串(还没进单词),再一路数字母,撞上单词左侧
//   第一个空格(或 i 走出 -1)收工。正序做必须扫完整串才知道谁是「最后」,
//   还得一路记账词边界;倒序只碰「尾部空格+末单词」一段,词间多空格、
//   前导空格全与它无关。和 88 逆序双指针同一句读题口诀:空位在尾倒着写,
//   答案在尾倒着读——方向相同,一个为不覆盖、一个为少走。
// 复杂度:
//   时间最坏 O(n)(全串一个单词/前导一大段空格),常态只碰尾部一小段;
//   空间 O(1)。暴力基线:split 全串切词取末尾,O(n) 时间 + O(n) 空间。
// 坑:
//   1. 串尾可能全是空格(示例2 末尾两个):从 s[n-1] 开始数之前必须先跳过
//      尾部空格,否则第一格就是「边界」,直接数出 0。
//   2. 悬空语句标本(未爆):原提交写 else l++; c++; 两行缩进对齐,看着
//      都在 else 里,实际只有 l++ 属于 else——c++ 悬空在循环体层,每轮
//      都会执行。本题恰好无害:空格且 c==0 走 continue 到不了这行,空格
//      且 c!=0 走 break 直接出循环,能落到它的只有字母分支——纯靠控制流
//      巧合兜底(与 12 的 'IV' 同款「编译器不吭声」),换个写法就 WA。
//      教训:if/else 体内多于一条语句,大括号必加,让缩进说实话;本入库
//      版已括上,与原版逐用例等价(2 万随机对拍验证)。
//   3. 双变量冗余:c 与 l 每次同步 +1,恒有 c==l——「是否已进单词」的
//      标志位和「单词长度」计数器是同一个数,计数器>0 本身就是标志,
//      一个变量够(两趟 while 精简骨架见 notes/字符串/倒序扫描.md)。
//   4. 边界:循环条件 i>=0 先于 s[i] 求值,短路挡 i=-1 的越界;int n=
//      s.size()-1 在空串会无符号下溢(语言参考自测20),本题由约束
//      1<=s.length() 且至少一个单词兜底。

class Solution {
public:
    int lengthOfLastWord(string s) {
        int n=s.size()-1;
        int l=0,c=0;                            // l:末单词长度  c:同步+1,兼「已进单词」标志(见坑3)

        for(int i=n;i>=0;i--)
        {
            if(s[i]==' '&&c==0)                 // 尾部空格:还没进单词,跳过
                continue;
            else if(s[i]==' '&&c!=0)            // 单词左边界:收工
                break;
            else
            {
                l++;
                c++;                            // 原提交悬空在 else 外,恰好无害(见坑2)
            }
        }
        return l;
    }
};
