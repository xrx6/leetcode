// 题号:0013  题名:罗马数字转整数  难度:简单
// 链接:https://leetcode.cn/problems/roman-to-integer/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(查表+相邻比较定加减,六条特例收编一条"左小右大减",待自己敲一遍 AC)
//
// 思路:
//   罗马数字是「符号流」:七个符号各带固定值 → 先建值表;真正待定的只有
//   一件事——每个符号前面是加号还是减号。题面掰开揉碎列了六种特例,但六
//   条全部长在「相邻两个符号的大小关系」上:左 ≥ 右,左边正常加;左 < 右,
//   左边是减法前缀(4 = IV:左边的 1 让右边的 5 变成「差一点」)。于是从
//   左往右一趟,每个字符瞄一眼右邻居:比自己大就减自己,否则加自己;末字
//   符没有右邻居,不可能是减法前缀,直接加。判据只比值、不比符号——
//   val[cur]<val[next] 一条规则收编六条特例(合法性下两者一一对应,原理见
//   notes/编码转换/相邻比较定加减.md)。
// 复杂度:
//   时间 O(n)  空间 O(1)(七个键的定表)
//   暴力基线:先把 IV→IIII、IX→VIIII……六种子串替换干净再全加,同样 O(n)
//   ——本题没有复杂度可坍缩(每个字符至少读一次是下界),难度全在规则压缩。
// 坑:
//   1. 顺着题面把六种特例翻译成六个 if:'I'&&(next=='V'||next=='X')……
//      十几个组合判断又长又容易漏;其实判断里不需要出现任何具体字符,只
//      比两格的值——特例是「哪些组合合法」的枚举,不是「怎么算」的规则。
//   2. peek next 的护栏必须排在短路口:i+1<n && val[s[i]]<val[s[i+1]],
//      条件写反顺序就先读 s[n] 越界。嫌护栏麻烦可换从右往左记 prev:prev
//      初值取 0,最右字符天然走加法,护栏被初值吃掉。
//   3. 从右往左是镜像规则「我比已处理的右邻小 → 减我」,减的是当前不是
//      prev:IX 右起 X 先 +10,I 比 X 小 −1 = 9;减错了对象成 +1−10 = −9。
//   4. val[s[i]] 敢用 operator[] 全靠题面「仅含七种字符」兜底:混入表外
//      字符会静默插入一个 0 值键(169 的访问即插入),不崩、答案悄悄错
//      ——约束拦得住运行时,拦不住代码形状,42 删判空同款话题。
class Solution {
public:
    int romanToInt(string s) {
        unordered_map<char,int> val = {{'I',1},{'V',5},{'X',10},{'L',50},
                                       {'C',100},{'D',500},{'M',1000}};   // 值表一步建全
        int n   = s.size();
        int ans = 0;
        for (int i = 0; i < n; i++)
        {
            if (i + 1 < n && val[s[i]] < val[s[i + 1]])   // 左小右大:我是减法前缀
            {
                ans -= val[s[i]];
            }
            else                                           // 其余(含末字符):正常加
            {
                ans += val[s[i]];
            }
        }
        return ans;
    }
};
