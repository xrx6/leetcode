// 题号:0012  题名:整数转罗马数字  难度:中等
// 链接:https://leetcode.cn/problems/integer-to-roman/?envType=study-plan-v2&envId=top-interview-150
// 状态:看题解后理解(13行降序面额表贪心能扣就扣,六种减法形式升格一等原子,待自己敲一遍 AC)
//
// 思路:
//   13 是解码(串→数),12 是反方向编码(数→串):解码靠找判据,编码靠
//   把规则压进数据。IV 在 13 里是两个原子加一条相邻规则,这里直接升格
//   为一个原子——七符号 + 六种减法形式 = 13 行面额表,按值降序。组合升
//   格为原子,是编码方向的通用一步。
//   算法是题面亲手递出来的:选能减去的最大面额、贴符号、扣值、重复。
//   从最大面额扫到最小,能扣就扣(while,同面额可重复——MMM),扣不动
//   换下一行,找零钱式贪心。
//   六条书写规则(4/9 用减法式、I/X/C 至多连三次、V/L/D 不重复)一条都
//   不用写成代码:面额表按位严格分层(9<10、90<100、900<1000),贪心
//   逐位清零,跨位写法(如 IL)根本没有原料;数位 ≤9,5 系至多扣一次、
//   1 系至多扣三次自动成立——规则是表的定理,不是代码的步骤(见 notes/
//   编码转换/贪心拆位.md)。
// 复杂度:
//   时间 O(1)  空间 O(1)(13 行定表)
//   num ≤ 3999,输出至多 15 个符号(最长 3888 = MMMDCCCLXXXVIII),连
//   while 扣减次数都有常数上界。暴力基线:逐位拆 + d==4/d==9 特判分
//   支;或 4×10 位串表(千/百/十/个各 10 串)直查拼串,免循环但表更
//   大。本题没有复杂度可坍缩(输入是定界整数,连 n 都没有),难度全在
//   「规则→数据」的搬运——13 压成一条判据,12 压成一张面额表。
// 坑:
//   1. 顺着题面把六条规则翻译成六类 if-else(4 用 IV、9 用 IX、连写至
//      多 3 次……):分支爆炸且相互纠缠;正确姿势是规则升格为数据,13 行
//      表一列,规则一条不写——与 13 坑 1 同源:题面枚举的是「合法性的
//      解释」,不是「计算的步骤」。
//   2. while 手滑写成 if:M/C/X/I 可能连扣至多 3 次,if 只扣一次,残数
//      被后面的小面额硬凑——3000 输出 "MCMDCDCXCX"(D 重复、位值乱序
//      的非法串),不崩、悄悄错;妙的是 13 的解码器读它照样得 3000,
//      「解码宽容/编码严格」的活标本。
//   3. 表必须降序:升序表从 I 开始,一排 I 把 num 扣到 0,大面额永远
//      轮不到(3749 → 3749 个 I)——贪心的方向由表的顺序承担。
//   4. val[]/sym[] 两张表靠人肉对齐,插漏一行就串位(900 配上 "XC");
//      可压成一张 pair 表内聚成一个下标,少一处对齐点。更彻底的是
//      4×10 位串表,连「位值」也压进数据——数据与代码的边界划在哪,
//      是风格选择。
class Solution {
public:
    string intToRoman(int num) {
        const int    val[13] = {1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1};
        const string sym[13] = {"M", "CM", "D", "CD", "C", "XC", "L",
                                "XL", "X", "IX", "V", "IV", "I"};   // 六种减法形式升格一等原子
        string ans;
        for (int i = 0; i < 13; i++)
        {
            while (num >= val[i])                                    // 贪心:当前面额能扣就扣
            {
                ans += sym[i];
                num  -= val[i];
            }
        }
        return ans;
    }
};
