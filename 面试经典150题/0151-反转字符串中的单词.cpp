// 思路:
//   题面是两层结构:「词的序列」和「词内字母」。要倒的是词序层,字母层不许动。
//   直球解(一):58 求「最后一个单词」从右扫,这题要「全部单词倒着报」——
//   同一副「跳空格→吃到词边界」的骨架,外面套层循环别停,从右往左收到的
//   词天然倒序;空格统一在词后补,末尾一刀。
//   进阶 O(1)(二):C++ 的 string 可变,题面「如果字符串是可变类型」就是
//   点名 C++。原地三步:① 快慢指针压实多余空格(27/80 直系:收的条件从
//   「≠val」变成组合条件「非空格必留;空格仅当保留区末尾不是空格才留」);
//   ② 整体翻一次——词序立刻倒转,代价是每个词内部字母也跟着倒;③ 逐词翻
//   回——翻转是对合,字母层翻两次=复原,词序层的翻转保留。这正是 189 三次
//   翻转的推广:那边两段 [A|B],这边 k 个词;「三次」其实是「整体一次+每段
//   一次」,段数=2 时才数出三。
// 复杂度:
//   时间均 O(n):解一 i 只左走,每格至多被「跳空格/吃词」看两遍,substr 拷词
//   总量 O(n);解二压实每格至多抄一次,整体翻+逐词翻=每字符至多被换 2 次。
//   空间:解一 O(n)(另开答案串);解二 O(1) ← 进阶要求。
//   基线:split 切词+逆序+join 也是 O(n)/O(n),库一把梭,考的就是手写。
// 坑:
//   1. 只整体翻一次不够:s 变 "eulb si yks eht"——整体翻两层全翻,逐词翻只
//      回滚字母层;这题的「反转」作用在词序层。
//   2. 词后补空格/词间留空格 ⇒ 末尾必多一格:解一 pop_back、解二 slow-- 加
//      resize,同一招「统一动作+末尾一刀」(哑结点家族)。解二忘删:resize 后
//      留尾部空格,整体翻变前导空格 WA;脚本验证失败集=全部含尾空格输入。
//   3. 哨兵只当信号,不当值:逐词翻循环条件 i<=n,收尾判据 i==n 放在 || 左
//      边短路,挡住右项 s[n] 的越界读——与 58 的 i>=0&&s[i] 同一招、挡的方向
//      相反(那边挡左溢,这边挡右溢)。坑总集「哨兵用<=」的病根是解引用哨兵,
//      不是 <= 本身。
//   4. 解一 if(i<0) break 是第二道岗:跳完空格若已出界(前导空格段),不
//      break 就把这段当「幽灵空词」收进来,答案多一格尾空格——内层 while 的
//      短路保的是「读」,外层 break 保的是「收」;脚本验证失败集=全部前导
//      空格输入,必爆。
//   5. 压实判据取 s[slow-1](保留区末尾)而非 s[fast-1](未爆,脚本验证本题
//      恰好等价):26 的纪律「和保留区比」原样适用。等价靠巧合——被丢的全是
//      空格,且丢的前提是它前面已有保留的空格;fast-1 若是字母则必刚被收下、
//      就停在 slow-1。纪律不靠巧合。另:解一 ans.pop_back()、int i=s.size()-1
//      靠约束兜底(至少一词⇒ans 非空;长度≥1 不下溢),全空格输入不在题域
//      内——解二对它优雅返回 ""(slow>0 守卫白给但留着不亏)。

// 解法一(倒序收词,58 倒序扫描的「不停版」;O(n)/O(n)):
class Solution {
public:
    string reverseWords(string s) {
        string ans;
        int i=s.size()-1;
        while(i>=0)
        {
            while(i>=0&&s[i]==' ') i--;          // 跳过词右侧空格:尾部/词间多余全在这消掉
            if(i<0) break;                       // 前导空格跳完已出界:别当「幽灵空词」收(坑4)
            int end=i;                           // 锚定词右端
            while(i>=0&&s[i]!=' ') i--;          // 一路吃到词左端外一格
            ans+=s.substr(i+1,end-i);            // 从右往左收到的词,天然倒序
            ans+=' ';                            // 词后统一补空格,末尾一刀(坑2)
        }
        ans.pop_back();                          // 去掉多补的那一个(约束保证 ans 非空)
        return ans;
    }
};

// 解法二(原地三步,进阶 O(1);提交时改名 Solution):
//   压实(快慢指针)→ 整体翻(词序倒转)→ 逐词翻回(字母复原)。
class Solution2 {
public:
    string reverseWords(string s) {
        int n=s.size(),slow=0;
        for(int fast=0;fast<n;fast++)                           // ① 压实:非空格必留
            if(s[fast]!=' '||(slow>0&&s[slow-1]!=' '))          //    空格仅当保留区末尾不是空格才留(坑5)
                s[slow++]=s[fast];
        if(slow>0&&s[slow-1]==' ') slow--;                      //    尾部恰好多留的一格(坑2)
        s.resize(slow);                                         //    砍掉废数据尾巴
        n=slow;

        reverse(s.begin(),s.end());                             // ② 整体翻:词序倒,词内字母跟着倒(坑1)

        for(int i=0,start=0;i<=n;i++)                           // ③ 逐词翻回:字母复原,词序不动
            if(i==n||s[i]==' ')                                 //    i==n 只当信号不当值,短路挡住 s[n](坑3)
            {
                reverse(s.begin()+start,s.begin()+i);
                start=i+1;
            }
        return s;
    }
};
